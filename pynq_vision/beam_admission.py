"""File/boot/resource admission for the fixed v14 PYNQ owner; no PYNQ import.

The protected current-boot receipt grants permission to read the already known
PL address map. It does NOT replace the subsequent actual halt/error/ABI reads.
No receipt is generated by --inspect or inferred from a historical boot UUID.
"""
import gzip
import hashlib
import json
import os
from pathlib import Path
import platform
import stat
import struct
import sys

GETTY_NAMES = frozenset(('agetty', 'getty', 'serial-getty', 'systemd-getty'))


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def inspect_bundle(manifest, overlay, library):
    record = json.loads(Path(manifest).read_text(encoding='utf-8'))
    if record.get('schema') != 'beam-pynq-hardware-v1' or record.get('csi_version') != 0x10001:
        raise RuntimeError('only frozen version14 CSI1.1 hardware is supported')
    from .constants import ADDRESS_MAP, FCLK_MHZ, BIT_SHA256, HWH_SHA256
    if (record.get('bit_sha256', '').lower() != BIT_SHA256.lower() or
            record.get('hwh_sha256', '').lower() != HWH_SHA256.lower() or
            record.get('addresses') != {name:list(value) for name,value in ADDRESS_MAP.items()} or
            record.get('fclk_mhz') != list(FCLK_MHZ) or record.get('ps_reference_hz') != 33333333):
        raise RuntimeError('manifest must retain the exact frozen hardware/address/clock profile')
    for path, expected in ((Path(overlay), record['bit_sha256']),
                           (Path(overlay).with_suffix('.hwh'), record['hwh_sha256']),
                           (Path(library), record['library_sha256'])):
        if sha(path) != expected:
            raise RuntimeError('mixed or changed deployment input: ' + str(path))
    if record['frame'] != dict(width=1280, height=720, row=3840, stride=5760, stores=3):
        raise RuntimeError('unsupported frame layout')
    return record


def validate_receipt(receipt, boot_id, record):
    if (receipt.get('schema') != 'beam-pynq-mmio-admission-v1' or
            receipt.get('boot_id') != boot_id or
            receipt.get('bit_sha256') != record['bit_sha256'] or
            receipt.get('hwh_sha256') != record['hwh_sha256'] or
            receipt.get('ps_reference_hz') != record['ps_reference_hz'] or
            not receipt.get('evidence_path') or
            len(receipt.get('evidence_sha256', '')) != 64):
        raise RuntimeError('current-boot matched PL/clock evidence required before MMIO')
    return receipt


def kernel_build_id(notes):
    offset = 0
    while offset + 12 <= len(notes):
        names, size, kind = struct.unpack_from('<III', notes, offset)
        offset += 12
        name = notes[offset:offset + names].rstrip(b'\0')
        offset += (names + 3) & ~3
        value = notes[offset:offset + size]
        offset += (size + 3) & ~3
        if name == b'GNU' and kind == 3:
            return value.hex()
    raise RuntimeError('kernel GNU Build-ID missing')


def conflicting_owners(proc=Path('/proc')):
    owners = []
    markers = ('/dev/mem', '/dev/xlnk', '/dev/uio', '/dev/dri/', '/dev/fb')
    for process in proc.iterdir():
        if not process.name.isdigit():
            continue
        try:
            paths = [os.readlink(str(fd)) for fd in (process / 'fd').iterdir()]
            maps = (process / 'maps').read_text(errors='replace')
            if any(marker in value for marker in markers for value in paths + [maps]):
                owners.append(int(process.name))
        except (FileNotFoundError, ProcessLookupError):
            pass
    return owners


def getty_targets_device(commandline, device):
    """Return whether a getty command line names this UART.

    A getty can be alive between service start and its first open(2), so an
    FD-only check is insufficient.  This helper is pure and deliberately
    accepts the command-line bytes shape exposed by Linux /proc.
    """
    if isinstance(commandline, bytes):
        commandline = commandline.decode('utf-8', errors='replace')
    words = str(commandline).replace('\0', ' ').split()
    if not words:
        return False
    executable = Path(words[0]).name
    if executable not in GETTY_NAMES and not executable.endswith('-getty'):
        return False
    names = (device.name, device.as_posix(), str(device))
    return any(token in names or token.rstrip(',') in names for token in words[1:])


def _uart_getty_pid(device, proc):
    for process in proc.iterdir():
        if not process.name.isdigit():
            continue
        try:
            commandline = (process / 'cmdline').read_bytes()
            if getty_targets_device(commandline, device):
                return int(process.name)
        except (FileNotFoundError, ProcessLookupError, PermissionError):
            pass
    return None


def check_uart_available(path, proc=Path('/proc')):
    device = Path(path).resolve()
    if device.name in ('console', 'tty', 'tty0'):
        raise RuntimeError('business UART cannot be a console alias')
    consoles = (proc / 'consoles').read_text()
    if any(line.split() and line.split()[0] == device.name for line in consoles.splitlines()):
        raise RuntimeError('UART is still a Linux kernel console; no boot parameter changed')
    if not stat.S_ISCHR(device.stat().st_mode):
        raise RuntimeError('explicit UART must be an existing character device')
    getty_pid = _uart_getty_pid(device, proc)
    if getty_pid is not None:
        raise RuntimeError('UART is reserved by getty PID {}; stop/reconfigure it outside this program'.format(getty_pid))
    for process in proc.iterdir():
        if not process.name.isdigit(): continue
        try:
            for fd in (process / 'fd').iterdir():
                if Path(os.readlink(str(fd))).resolve() == device:
                    raise RuntimeError('UART already held by PID ' + process.name)
        except (FileNotFoundError, ProcessLookupError):
            pass


def preflight(record, receipt_path, i2c_device):
    if sys.platform != 'linux' or platform.machine() != 'armv7l' or os.geteuid() != 0:
        raise RuntimeError('explicit root ARMv7 Linux board execution required')
    if sys.version_info[:2] != (3, 6):
        raise RuntimeError('this frozen PYNQ2.6.2 environment targets Python3.6')
    boot = Path('/proc/sys/kernel/random/boot_id').read_text().strip()
    receipt_path = Path(receipt_path)
    identity = receipt_path.lstat()
    if (not stat.S_ISREG(identity.st_mode) or identity.st_uid != 0 or
            identity.st_nlink != 1 or identity.st_mode & 0o022):
        raise RuntimeError('admission must be a protected root-owned regular file')
    receipt = validate_receipt(json.loads(receipt_path.read_text()), boot, record)
    evidence = Path(receipt['evidence_path'])
    identity = evidence.lstat()
    if (not stat.S_ISREG(identity.st_mode) or identity.st_uid != 0 or
            identity.st_nlink != 1 or identity.st_mode & 0o022 or
            sha(evidence) != receipt['evidence_sha256']):
        raise RuntimeError('protected current-boot MMIO evidence changed/missing')
    proof = json.loads(evidence.read_text())
    if (proof.get('schema') != 'beam-pynq-quiesced-v1' or proof.get('boot_id') != boot or
            proof.get('bit_sha256') != record['bit_sha256'] or
            proof.get('hwh_sha256') != record['hwh_sha256']):
        raise RuntimeError('MMIO evidence is not for this boot and matched PL')
    for role in ('capture', 'display'):
        registers = proof['dma'][role]
        control, status = registers['control'], registers['status']
        if type(control) is not int or type(status) is not int or control & 1 or not status & 1 or status & 0x89f0:
            raise RuntimeError('admission lacks actual clean HALTED register evidence')
    if platform.release() != record['kernel_release']:
        raise RuntimeError('kernel release differs')
    if kernel_build_id(Path('/sys/kernel/notes').read_bytes()) != record['kernel_build_id']:
        raise RuntimeError('running kernel differs from identified xlnk implementation')
    config = gzip.decompress(Path('/proc/config.gz').read_bytes())
    if hashlib.sha256(config).hexdigest() != record['kernel_config_sha256']:
        raise RuntimeError('kernel config differs')
    if sha('/boot/image.ub') != record['fit_sha256']:
        raise RuntimeError('boot kernel image differs')
    for relative, digest in record['pynq_sources'].items():
        if sha(Path('/home/xilinx/pynq') / relative) != digest:
            raise RuntimeError('installed PYNQ implementation differs: ' + relative)
    bus = Path(i2c_device).name
    if not bus.startswith('i2c-') or 'e0004000' not in str((Path('/sys/class/i2c-dev') / bus / 'device').resolve()):
        raise RuntimeError('explicit I2C device must resolve to PS I2C0/e0004000')
    owners = conflicting_owners()
    if owners:
        raise RuntimeError('pre-existing device/CMA owners must be stopped separately: ' + repr(owners))
    if not Path('/sys/class/fpga_manager/fpga0/firmware').exists():
        raise RuntimeError('PYNQ FPGA-manager load path unavailable; no fallback loader')
    return boot
